NID_HMAC_KEY = env("NID_HMAC_KEY", required=True)
if len(NID_HMAC_KEY) < 32 or len(SECRET_KEY) < 32:
    raise ImproperlyConfigured("DJANGO_SECRET_KEY and NID_HMAC_KEY must be at least 32 characters")
if NID_HMAC_KEY == SECRET_KEY:
    raise ImproperlyConfigured("NID_HMAC_KEY must differ from DJANGO_SECRET_KEY")

